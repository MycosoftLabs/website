function hasExplicitBoxClass(className?: string): boolean {
  return Boolean(className && /\b(h-|w-|size-|min-h-|min-w-)/.test(className))
}

function flatSrc(product: ProductMarkId, tone: "black" | "white"): string {
  return `/icons/mycosoft/${tone}/${product}.svg`
}

function glassSrc(product: ProductMarkId, tone: "light" | "dark"): string {
  // MYCA dark: Morgan's frosted clear PNG (black mark on frosted face).
  // MYCA light: same colored glass treatment as NLM / FormSpace.
  if (product === "myca" && tone === "dark") {
    return "/icons/mycosoft/glass/myca-glass-frosted-black.png"
  }
  return `/icons/mycosoft/glass/${tone}/${product}.png`
}

/**
 * Lucide-compatible product mark: a single <svg> with fill="currentColor".
 * Same DOM contract as Shield/Database — `h-4 w-4` is a true square, glyph fills it.
 */
function CurrentMarkSvg({
  product,
  className,
  title,
  size = 16,
  ...rest
}: {
  product: ProductMarkId
  className?: string
  title?: string
  size?: number
} & Omit<SVGProps<SVGSVGElement>, "children">) {
  const mark = PRODUCT_MARK_SVG[product]
  const explicitBox = hasExplicitBoxClass(className)
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={mark.viewBox}
      preserveAspectRatio="xMidYMid slice"
      fill="currentColor"
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
      aria-label={title}
      width={explicitBox ? undefined : size}
      height={explicitBox ? undefined : size}
      className={cn(
        // Lucide-sized square; slice fills the box; clip so tips stay inside lockup.
        "lucide shrink-0 block size-full max-h-full max-w-full aspect-square overflow-hidden",
        !explicitBox && "size-4",
        className
      )}
      {...rest}
    >
      {mark.paths.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  )
}

/**
 * Square product mark — nav uses variant="current" (default) like Lucide.
 * Glass is for showcase heroes only.
 */
export function ProductIcon({
  product,
  className,
  title,
  size = 16,
  variant = "current",
}: ProductIconProps) {
  if (variant === "current") {
    return (
      <CurrentMarkSvg
        product={product}
        className={className}
        title={title}
        size={size}
      />
    )
  }

  const explicitBox = hasExplicitBoxClass(className)
  const boxStyle: CSSProperties | undefined = explicitBox
    ? undefined
    : { width: size, height: size }
  const boxClass = cn(
    "relative inline-block shrink-0 overflow-hidden aspect-square bg-transparent",
    !explicitBox && "size-4",
    className
  )
  const a11y = {
    "aria-hidden": title ? undefined : (true as const),
    role: title ? ("img" as const) : undefined,
    "aria-label": title,
  }

  if (variant === "glass") {
    return (
      <span className={boxClass} style={boxStyle} {...a11y}>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={glassSrc(product, "light")}
          alt=""
          className="absolute inset-0 block size-full object-cover dark:hidden"
          draggable={false}
        />
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={glassSrc(product, "dark")}
          alt=""
          className="absolute inset-0 hidden size-full object-cover dark:block"
          draggable={false}
        />
      </span>
    )
  }

  if (variant === "black" || variant === "white") {
    return (
      <span className={boxClass} style={boxStyle} {...a11y}>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={flatSrc(product, variant)}
          alt=""
          className="absolute inset-0 block size-full object-cover"
          draggable={false}
        />
      </span>
    )
  }

  // auto: black/white bitmap swap
  return (
    <span className={boxClass} style={boxStyle} {...a11y}>
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        src={flatSrc(product, "black")}
        alt=""
        className="absolute inset-0 block size-full object-cover dark:hidden"
        draggable={false}
      />
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        src={flatSrc(product, "white")}
        alt=""
        className="absolute inset-0 hidden size-full object-cover dark:block"
        draggable={false}
      />
    </span>
  )
}

/**
 * Lucide-compatible factory for nav configs.
 * Always `current` — glass is blocked so dropdowns stay flat monochrome.
 * Renders the same single <svg> element shape as Lucide icons.
 */
export function productMarkIcon(
  product: ProductMarkId,
  _sizeHint = 16,
  variant: ProductIconVariant = "current"
) {
  const safeVariant: ProductIconVariant = variant === "glass" ? "current" : variant
  function MarkIcon({ className }: { className?: string }) {
    return <ProductIcon product={product} className={className} variant={safeVariant} />
  }
  MarkIcon.displayName = `ProductMark(${product})`
  return MarkIcon
}
